import { getDocumentTemplates, getAllDocuments } from "@/features/documents/actions"
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card"
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs"
import { Badge } from "@/components/ui/badge"
import { Button, buttonVariants } from "@/components/ui/button"
import { FileText, Plus, FileSymlink, Settings } from "lucide-react"
import Link from "next/link"

export default async function DocumentsDashboardPage() {
  const [templatesRes, documentsRes] = await Promise.all([
    getDocumentTemplates(),
    getAllDocuments()
  ])

  const templates = templatesRes.data || []
  const documents = documentsRes.data || []

  return (
    <div className="flex-1 space-y-4 p-4 pt-6 md:p-8">
      <div className="flex items-center justify-between space-y-2">
        <h2 className="text-3xl font-bold tracking-tight">Documents</h2>
        <div className="flex items-center space-x-2">
          <Link href="/dashboard/documents/templates/add" className={buttonVariants()}>
            <Plus className="mr-2 h-4 w-4" /> Create Template
          </Link>
        </div>
      </div>

      <Tabs defaultValue="templates" className="space-y-4">
        <TabsList>
          <TabsTrigger value="templates">Document Templates</TabsTrigger>
          <TabsTrigger value="archive">Generated Archive</TabsTrigger>
        </TabsList>

        <TabsContent value="templates" className="space-y-4">
          {templates.length === 0 ? (
            <div className="text-center p-12 border rounded-lg bg-muted/20 border-dashed">
              <FileText className="w-10 h-10 text-muted-foreground mx-auto mb-4" />
              <h3 className="text-lg font-medium mb-1">No Templates Found</h3>
              <p className="text-muted-foreground mb-4">Create your first document template to start generating letters and reports.</p>
              <Link href="/dashboard/documents/templates/add" className={buttonVariants()}>
                Create Template
              </Link>
            </div>
          ) : (
            <div className="grid gap-4 md:grid-cols-2 lg:grid-cols-3">
              {templates.map(template => (
                <Card key={template.id}>
                  <CardHeader className="pb-3">
                    <div className="flex justify-between items-start">
                      <div>
                        <CardTitle className="text-lg">{template.name}</CardTitle>
                        <Badge variant="outline" className="mt-1">{template.type}</Badge>
                      </div>
                      <Button variant="ghost" size="icon">
                        <Settings className="w-4 h-4" />
                      </Button>
                    </div>
                  </CardHeader>
                  <CardContent>
                    <p className="text-xs text-muted-foreground mb-4">
                      Last updated {new Date(template.updatedAt).toLocaleDateString()}
                    </p>
                    <div className="flex gap-2">
                      <Button variant="secondary" className="w-full text-xs" size="sm">Edit Template</Button>
                    </div>
                  </CardContent>
                </Card>
              ))}
            </div>
          )}
        </TabsContent>

        <TabsContent value="archive" className="space-y-4">
          <Card>
            <CardHeader>
              <CardTitle>Recent Documents</CardTitle>
              <CardDescription>Archive of all generated documents across the system.</CardDescription>
            </CardHeader>
            <CardContent>
              {documents.length === 0 ? (
                <div className="text-center py-6 text-sm text-muted-foreground">
                  No documents have been generated yet.
                </div>
              ) : (
                <div className="space-y-4">
                  {documents.map(doc => (
                    <div key={doc.id} className="flex justify-between items-center p-3 border rounded-lg hover:bg-muted/50 transition-colors">
                      <div className="flex items-center gap-3">
                        <div className="bg-primary/10 p-2 rounded">
                          <FileSymlink className="w-4 h-4 text-primary" />
                        </div>
                        <div>
                          <p className="font-medium text-sm">
                            <Link href={`/dashboard/documents/${doc.id}`} className="hover:underline">
                              {doc.title}
                            </Link>
                          </p>
                          <p className="text-xs text-muted-foreground">
                            Generated by {doc.user.name} on {new Date(doc.createdAt).toLocaleString()}
                          </p>
                        </div>
                      </div>
                      <div className="flex gap-2">
                        {doc.case && <Badge variant="outline">Case {doc.case.referenceNumber}</Badge>}
                        {doc.student && <Badge variant="secondary">{doc.student.firstName} {doc.student.lastName}</Badge>}
                      </div>
                    </div>
                  ))}
                </div>
              )}
            </CardContent>
          </Card>
        </TabsContent>
      </Tabs>
    </div>
  )
}
