"use client"

import { Button } from "@/components/ui/button"
import { Printer, Download } from "lucide-react"
import jsPDF from "jspdf"
import html2canvas from "html2canvas"
import { useRef, useState } from "react"

interface DocumentViewerProps {
  title: string
  content: string
  date: Date
  authorName: string
}

export function DocumentViewer({ title, content, date, authorName }: DocumentViewerProps) {
  const documentRef = useRef<HTMLDivElement>(null)
  const [isGenerating, setIsGenerating] = useState(false)

  const handlePrint = () => {
    window.print()
  }

  const handleDownloadPDF = async () => {
    if (!documentRef.current) return
    setIsGenerating(true)
    
    try {
      const canvas = await html2canvas(documentRef.current, { scale: 2 })
      const imgData = canvas.toDataURL("image/png")
      
      const pdf = new jsPDF("p", "mm", "a4")
      const pdfWidth = pdf.internal.pageSize.getWidth()
      const pdfHeight = (canvas.height * pdfWidth) / canvas.width
      
      pdf.addImage(imgData, "PNG", 0, 0, pdfWidth, pdfHeight)
      pdf.save(`${title.replace(/\s+/g, '_')}.pdf`)
    } catch (error) {
      console.error("PDF generation failed", error)
    } finally {
      setIsGenerating(false)
    }
  }

  return (
    <div className="flex flex-col h-full bg-slate-100 dark:bg-slate-900 overflow-hidden relative">
      <div className="flex justify-between items-center p-4 bg-background border-b print:hidden">
        <div>
          <h2 className="text-lg font-semibold">{title}</h2>
          <p className="text-xs text-muted-foreground">Generated by {authorName} on {new Date(date).toLocaleString()}</p>
        </div>
        <div className="flex gap-2">
          <Button variant="outline" size="sm" onClick={handlePrint} disabled={isGenerating}>
            <Printer className="w-4 h-4 mr-2" />
            Print
          </Button>
          <Button variant="default" size="sm" onClick={handleDownloadPDF} disabled={isGenerating}>
            <Download className="w-4 h-4 mr-2" />
            {isGenerating ? "Generating..." : "Download PDF"}
          </Button>
        </div>
      </div>
      
      <div className="flex-1 overflow-auto p-8 print:p-0 print:overflow-visible flex justify-center">
        {/* A4 Paper Simulation */}
        <div 
          ref={documentRef}
          className="bg-white text-black p-10 md:p-16 shadow-xl print:shadow-none mx-auto print:mx-0 w-[210mm] min-h-[297mm] print:w-auto print:min-h-0 print:h-auto font-serif"
        >
          <div 
            className="prose max-w-none prose-sm"
            dangerouslySetInnerHTML={{ __html: content }} 
          />
        </div>
      </div>

      <style jsx global>{`
        @media print {
          body * {
            visibility: hidden;
          }
          .print\\:hidden {
            display: none !important;
          }
          .font-serif, .font-serif * {
            visibility: visible;
          }
          .font-serif {
            position: absolute;
            left: 0;
            top: 0;
            width: 100%;
            padding: 2cm !important;
          }
        }
      `}</style>
    </div>
  )
}
